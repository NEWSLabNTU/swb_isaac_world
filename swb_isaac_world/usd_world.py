"""An Isaac world file for a USD world (roadmap 038): `python -m swb_isaac_world.usd_world`.

For a world exported from CARLA with NVIDIA's SimReady converter (CARLA 0.9.16's editor,
`UE4Editor-Cmd ... -run=SimReadyExport`): its frame is already the Autoware map frame (the
exporter converts centimetres to metres and flips CARLA's Y), so `map_origin` is zero. The
exporter writes no colliders; a physics layer that sublayers the export and applies
`CollisionAPI` to its meshes is the file to use.

`ground_paths` -- what a body rests on, whose contacts are not reported (037) -- come from
the stage's SimReady semantic labels (`semantics:labels:wikidata_qcode`): roads, sidewalks,
road markings, terrain and ground, plus the unlabelled landscape. A parked car, a wall or a
pole the ego touches is still a contact.

Writes `<map dir>/isaac/world.yaml`, replacing the point-cloud voxel world's
(`swb_isaac_world.pcd_world`; run that again to switch back). Its `usd:` is a name, not a
host's path, where it can be (`usd_name`): `${SWB_CARLA_USD}/<Town>/...` for a stage in the
CARLA USD set, relative for one inside the map directory, absolute otherwise. `make_world`
runs this, and the export and the physics layer before it.

    python -m swb_isaac_world.usd_world data/carla-autoware-bridge/Town01 \\
        /mnt/disk1/carla-usd/Town01/Town01_physics.usda
"""
import argparse
import os
import sys
from pathlib import Path

from .surfaces import QCODE_LABELS

# Wikidata Q-codes SimReady writes for CARLA's ground classes (CARLA docs, nvidia_simready)
GROUND_QCODES = set(QCODE_LABELS)
QCODE_ATTR = "semantics:labels:wikidata_qcode"
# Where world.py references the world's default prim.
ENVIRONMENT = "/World/env"


def ground_paths(stage):
    """The top-most prims labelled as ground, and the landscape, as stage paths under
    ENVIRONMENT (the world is referenced there)."""
    from pxr import Usd

    root = stage.GetDefaultPrim()
    found = []
    it = iter(Usd.PrimRange(root))
    for prim in it:
        attr = prim.GetAttribute(QCODE_ATTR)
        labels = set(attr.Get() or []) if attr else set()
        if labels & GROUND_QCODES or prim.GetName().startswith("Landscape"):
            found.append(prim.GetPath())
            it.PruneChildren()
    prefix = str(root.GetPath())
    return [ENVIRONMENT + str(p)[len(prefix):] for p in found]


def usd_name(usd, map_dir, env=None):
    """How a world file names stage `usd`: `${SWB_CARLA_USD}/<rel>` under the CARLA USD set's
    root (`names.carla_usd_root`), relative under the map directory, else absolute."""
    from . import names

    usd = os.path.abspath(usd)
    root = names.carla_usd_root(env)
    for base, prefix in ((map_dir, ""), (root, "${" + names.CARLA_USD_ENV + "}/")):
        if not base:
            continue
        for b in dict.fromkeys((os.path.abspath(os.path.expanduser(base)),
                                os.path.realpath(os.path.expanduser(base)))):
            rel = os.path.relpath(usd, b)
            if not rel.startswith(".."):
                return prefix + rel
            rel = os.path.relpath(os.path.realpath(usd), b)
            if not rel.startswith(".."):
                return prefix + rel
    return usd


def world_yaml(usd_text, paths):
    """A world file's text: stage `usd_text`, map origin zero, `paths` as its ground."""
    lines = [
        "# Generated by swb_isaac_world.usd_world (roadmap 038): a USD world in the Autoware map frame",
        "# (CARLA's SimReady export: metres, Y already flipped), ground from its semantic labels.",
        f"usd: {usd_text}",
        "map_origin: [0.0, 0.0, 0.0]",
        "ground_paths:",
        *[f'  - "{p}"' for p in paths],
    ]
    return "\n".join(lines) + "\n"


def write(map_dir, usd, out=None):
    """Write the world file for stage `usd` (`out`, default `<map dir>/isaac/world.yaml`):
    (its path, the ground prims' count). Needs pxr."""
    from pxr import Usd

    stage = Usd.Stage.Open(os.path.abspath(usd))
    if not stage or not stage.GetDefaultPrim():
        raise ValueError(f"{usd}: no stage or no default prim")
    paths = ground_paths(stage)
    out = Path(out) if out else Path(map_dir) / "isaac" / "world.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(world_yaml(usd_name(usd, map_dir), paths))
    return out, len(paths)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("map_dir")
    ap.add_argument("usd", help="the world: CARLA's SimReady export with its physics layer")
    args = ap.parse_args(argv)
    try:
        out, n = write(args.map_dir, args.usd)
    except ValueError as e:
        sys.exit(str(e))
    print(f"{n} ground prim(s); wrote {out}")


if __name__ == "__main__":
    sys.exit(main())
